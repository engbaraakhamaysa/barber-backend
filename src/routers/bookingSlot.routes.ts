import { Router } from "express";
import { BookingSlotController } from "../controllers/bookingSlot.controller";

const router = Router();

/////////////////////////////////////////////////////////
//              CREATE SLOTS (BULK INSERT)             //
/////////////////////////////////////////////////////////

router.post("/slots", BookingSlotController.createSlots);

/////////////////////////////////////////////////////////
//            GET ALL SLOTS BY BARBER ID              //
/////////////////////////////////////////////////////////

router.get("/slots/:barber_id", BookingSlotController.getAllByBarber);

/////////////////////////////////////////////////////////
//                    DELETE SLOT                     //
/////////////////////////////////////////////////////////

router.delete("/slots/:slot_id", BookingSlotController.deleteSlot);

/////////////////////////////////////////////////////////
//                     BOOK SLOT                      //
/////////////////////////////////////////////////////////

router.post("/slots/book", BookingSlotController.bookSlot);

export default router;
