import { Router } from "express";
import { BarberController } from "../controllers/barber.controller";

const router = Router();

/////////////////////////////////////////////////////////
//                 CREATE BARBER                       //
/////////////////////////////////////////////////////////

router.post("/", BarberController.create);

/////////////////////////////////////////////////////////
//              GET BARBERS BY SHOP ID                //
/////////////////////////////////////////////////////////

router.get("/:id", BarberController.getByShopId);

/////////////////////////////////////////////////////////
//                 UPDATE BARBER                      //
/////////////////////////////////////////////////////////

router.put("/", BarberController.update);

/////////////////////////////////////////////////////////
//                 DELETE BARBER                      //
/////////////////////////////////////////////////////////

router.delete("/:id", BarberController.deleteById);

router.post("/login", BarberController.login);

export default router;
